#include "libft.h"

int	ft_atoi(const char *c)
{
	int	s;
	int	n;

	n = 0;
	s = 1;
	while (*c == ' ' || (*c >= 9 && *c <= 13))
		c++;
	if (*c == '-' || *c == '+')
	{
		if (*c == '-')
			s = -1;
		c++;
	}
	while (*c >= '0' && *c <= '9')
	{
		n = n * 10 + (*c - '0');
		c++;
	}
	return (n * s);
}
